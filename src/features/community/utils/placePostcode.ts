const KNOWN_PLACE_POSTCODES = KNOWN_PLACE_POSTCODE_LABELS.reduce<Record<string, string>>(
  (accumulator, [place, postcode]) => {
    accumulator[normalizePlacePostcodeKey(place)] = postcode;
    accumulator[normalizePlacePostcodeKey(place.replace(STATE_SUFFIX_PATTERN, ""))] = postcode;
    return accumulator;
  },
  {}
);

export const formatPlaceWithPostcode = (place: string) => {
  const trimmedPlace = place.replace(/\s+/g, " ").trim();
  if (!trimmedPlace || AUSTRALIAN_POSTCODE_PATTERN.test(trimmedPlace)) {
    return trimmedPlace;
  }

  const postcode = KNOWN_PLACE_POSTCODES[normalizePlacePostcodeKey(trimmedPlace)];
  return postcode ? `${trimmedPlace} ${postcode}` : trimmedPlace;
};
